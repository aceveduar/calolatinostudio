// Manual "Cómo se usa": se abre desde Más, se busca, los temas se abren con pasos y captura; cada rol ve lo suyo.
import { chromium } from 'playwright-core';
import { revisarPagina } from './revisar.mjs';
const OUT = new URL('./salida/', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const ok = (c) => (c ? 'OK' : 'MAL');
const b = await chromium.launch({ channel: 'msedge' });
const p = await (await b.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, locale: 'es-MX' })).newPage();
const errores = []; p.on('pageerror', (e) => errores.push(e.message));
await p.goto('http://localhost:4173/');
await p.waitForFunction(() => !!window.compasDev);
await p.evaluate(() => window.compasDev.demoCompleta());
await p.reload();
await p.getByText('Monse', { exact: true }).click();
await p.keyboard.type('1111', { delay: 30 });
await p.waitForTimeout(1200);
await p.getByRole('link', { name: 'Más' }).first().click();
await p.getByRole('link', { name: /Cómo se usa/ }).click();
await p.getByRole('heading', { name: 'Cómo se usa' }).waitFor();
await p.screenshot({ path: `${OUT}manual-1.png` });
await p.getByRole('button', { name: /Corte de caja/ }).click();
await p.waitForTimeout(800);
await p.screenshot({ path: `${OUT}manual-2.png`, fullPage: true });
await p.getByLabel('Buscar en el manual').fill('ticket');
await p.waitForTimeout(400);
const t = (await p.locator('main').innerText()).replace(/\s+/g, ' ');
const imagen = await p.locator('img[alt^="Pantalla de ejemplo"]').count();
console.log('1) buscar "ticket" encuentra el tema y recepción no ve temas del dueño:', ok(/Mandar el ticket de compra/.test(t) && !/Reportes: ¿cómo vamos\?/.test(t)));
const r = await revisarPagina(p);
console.log('2) sin desbordes, botones con nombre y buen contraste:', ok(!r.ancho && !r.sinNombre.length && !r.contraste?.length), JSON.stringify({ ancho: r.ancho, sinNombre: r.sinNombre, contraste: r.contraste }));
await p.getByRole('link', { name: 'Más' }).first().click();
await p.getByRole('link', { name: /Ayuda y errores/ }).waitFor({ timeout: 5000 }).catch(() => {});
console.log('3) "Ayuda y errores" ahora sí está en Más:', ok((await p.getByRole('link', { name: /Ayuda y errores/ }).count()) === 1));
console.log('errores:', errores.length ? errores : 'ninguno');
await b.close();
