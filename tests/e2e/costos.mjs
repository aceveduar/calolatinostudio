import { chromium } from 'playwright-core';
const OUT = new URL('./salida/', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const browser = await chromium.launch({ channel: 'msedge' });
const page = await (await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, locale: 'es-MX' })).newPage();
await page.clock.install({ time: new Date('2026-11-13T19:30:00') });
const errores = []; page.on('pageerror', (e) => errores.push(e.message));
const ok = (c) => (c ? 'OK' : 'MAL');
const dlg = page.getByRole('dialog');
const ir = (r) => page.evaluate((x) => { history.pushState(null, '', x); dispatchEvent(new PopStateEvent('popstate')); }, r);
await page.goto('http://localhost:4173/');
await page.waitForFunction(() => !!window.compasDev);
await page.evaluate(async () => { await window.compasDev.sembrar(); await window.compasDev.agregarClasesDemo(); await window.compasDev.agregarTiendaDemo(); });
await page.reload();
await page.getByText('Dirección Calo', { exact: true }).click();
for (const d of '1234') await page.getByRole('button', { name: d, exact: true }).click();
await page.getByPlaceholder(/Quién llegó|Buscar…/).waitFor();
await ir('/ajustes/productos');
await page.getByText('Agua 600 ml').waitFor();
const fila = (await page.locator('main').innerText()).replace(/\s+/g, ' ');
console.log('1) la lista muestra cuánto deja:', ok(/Agua 600 ml Snacks y bebidas · deja \$8/.test(fila)));
await page.getByText('Agua 600 ml').click();
const margen = (await dlg.innerText()).replace(/\s+/g, ' ');
console.log('2) el producto muestra ganancia y margen:', ok(/Te deja \$8 por pieza \(53% del precio\)/.test(margen)));
await dlg.getByPlaceholder('$ costo por pieza').fill('20');
await page.waitForTimeout(100);
console.log('3) avisa si se vende abajo del costo:', ok((await dlg.getByText(/Ojo: lo vendes \$5 abajo del costo/).count()) === 1));
await page.keyboard.press('Escape');
// venta nueva guarda su costo
await page.getByRole('link', { name: 'Entrada' }).first().click();
await page.getByRole('button', { name: /^Tienda/ }).click();
await dlg.getByRole('button', { name: /Agregar Agua 600 ml/ }).click();
await page.waitForTimeout(400);
const costo = await page.evaluate(() => new Promise((res) => { const q = indexedDB.open('compas'); q.onsuccess = () => { q.result.transaction('pagos').objectStore('pagos').getAll().onsuccess = (e) => res(e.target.result.sort((a, b) => b.createdAt - a.createdAt)[0].costo); }; }));
console.log('4) la venta guarda su costo ($7):', ok(costo === 700), costo);
await page.keyboard.press('Escape');
await page.getByRole('link', { name: 'Reportes' }).first().click();
await page.getByText(/Te dejó/).first().waitFor();
const rep = (await page.locator('main').innerText()).replace(/\s+/g, ' ');
console.log('5) reportes: vendido y ganancia de la tienda:', ok(/TIENDA Vendido \$[\d,]+ Te dejó \$[\d,]+/i.test(rep)), (rep.match(/TIENDA Vendido .{0,60}/i) || [])[0]);
await page.getByText(/Te dejó/).first().scrollIntoViewIfNeeded();
await page.screenshot({ path: `${OUT}costos-reportes.png` });
console.log('errores:', errores.length ? errores : 'ninguno');
await browser.close();
