import { chromium } from 'playwright-core';
const OUT = new URL('./salida/', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const browser = await chromium.launch({ channel: 'msedge' });
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, locale: 'es-MX' });
await ctx.route('https://wa.me/**', (r) => r.fulfill({ body: 'wa' }));
const page = await ctx.newPage();
const errores = []; page.on('pageerror', (e) => errores.push(e.message));
const ok = (c) => (c ? 'OK' : 'MAL');
const ir = (r) => page.evaluate((x) => { history.pushState(null, '', x); dispatchEvent(new PopStateEvent('popstate')); }, r);
await page.goto('http://localhost:4173/');
await page.waitForFunction(() => !!window.compasDev);
await page.evaluate(() => window.compasDev.sembrar());
await page.reload();
await page.getByText('Dirección Calo', { exact: true }).click();
for (const d of '1234') await page.getByRole('button', { name: d, exact: true }).click();
await page.getByPlaceholder(/Quién llegó|Buscar…/).waitFor();
// 1) Editar el mensaje "Te extrañamos"
await ir('/ajustes/mensajes');
await page.getByText('Te extrañamos', { exact: true }).waitFor();
await page.screenshot({ path: `${OUT}msg-1-lista.png`, fullPage: true });
const tarjeta = page.locator('div.rounded-2xl').filter({ hasText: 'Para quien dejó de venir' });
await tarjeta.getByRole('button', { name: 'Editar' }).click();
await page.getByLabel('Mensaje: Te extrañamos').fill('¡{nombre}! En {academia} te guardamos tu lugar en la pista 🔥 ');
await page.waitForTimeout(200);
const previa = await tarjeta.innerText();
console.log('1) vista previa con datos reemplazados:', ok(previa.includes('¡Ana! En Calo Latino Studio te guardamos tu lugar')));
await page.screenshot({ path: `${OUT}msg-2-editar.png`, fullPage: true });
await tarjeta.getByRole('button', { name: 'Guardar' }).click();
await page.getByText('Mensaje guardado').waitFor();
// 2) Ficha → WhatsApp: los 5 mensajes con el editado
await ir('/alumnos');
await page.getByPlaceholder('Buscar por nombre o teléfono').fill('Carlos Ruiz');
await page.getByText('Carlos Ruiz').click();
await page.getByRole('button', { name: 'WhatsApp' }).click();
const dlg = page.getByRole('dialog');
await dlg.getByText('Bienvenida').waitFor();
await page.screenshot({ path: `${OUT}msg-3-ficha.png` });
const enlaces = await dlg.locator('a').evaluateAll((as) => as.map((a) => decodeURIComponent(a.href.split('text=')[1] ?? '')));
console.log('2) opciones en la ficha:', enlaces.length, '· usa el texto editado:', ok(enlaces.some((t) => t.startsWith('¡Carlos! En Calo Latino Studio te guardamos'))));
console.log('   bienvenida:', enlaces[0]);
await page.keyboard.press('Escape');
// 3) Vender plan → aviso "Enviar recibo"
await page.getByRole('button', { name: 'Vender plan' }).click();
await page.getByRole('dialog').getByRole('button', { name: /Cobrar \$/ }).click();
const boton = page.getByRole('button', { name: 'Enviar recibo' });
await boton.waitFor({ timeout: 5000 });
await page.screenshot({ path: `${OUT}msg-4-recibo.png` });
const pest = ctx.waitForEvent('page');
await boton.click();
const p = await pest; await p.waitForURL(/wa\.me/, { timeout: 8000 }).catch(() => {});
const recibo = decodeURIComponent(p.url().split('text=')[1] ?? '');
console.log('3) recibo:', recibo, ok(/recibimos tu pago de \$\d+ por (mensualidad|paquete)/i.test(recibo) && / al /.test(recibo)));
console.log('errores:', errores.length ? errores : 'ninguno');
await browser.close();
