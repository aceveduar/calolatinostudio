import { chromium } from 'playwright-core';
const DIR = new URL('./', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1');
const ok = (c) => (c ? 'OK' : 'MAL');
const browser = await chromium.launch({ channel: 'msedge' });
const page = await (await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true, locale: 'es-MX' })).newPage();
await page.clock.install({ time: new Date('2026-11-13T19:30:00') });
const errores = []; page.on('pageerror', (e) => errores.push(e.message));
await page.route(/rest\/v1\//, (r) => r.fulfill({ status: 201, body: '[]' }));
await page.goto('http://localhost:4173/');
await page.waitForFunction(() => !!window.compasDev);
await page.evaluate(async () => { await window.compasDev.sembrar(); await window.compasDev.agregarClasesDemo(); await window.compasDev.agregarTiendaDemo(); });
await page.reload();
await page.getByText('Dirección Calo', { exact: true }).click();
await page.keyboard.type('1234', { delay: 30 });
await page.getByPlaceholder(/Quién llegó|Buscar…/).waitFor();
await page.evaluate(() => { history.pushState(null, '', '/ajustes/productos'); dispatchEvent(new PopStateEvent('popstate')); });
const dlg = page.getByRole('dialog');
await page.getByRole('button', { name: 'Nuevo producto' }).click();
await dlg.getByText('Sin foto', { exact: true }).waitFor();
const formularioSimple = await dlg.getByText(/ícono/i).count() === 0;
await dlg.getByPlaceholder('Ej. Agua 600 ml').fill('Producto sin foto');
await dlg.getByPlaceholder('$', { exact: true }).fill('25');
await dlg.getByRole('button', { name: 'Guardar' }).click();
await dlg.waitFor({ state: 'hidden' });
const nuevo = await page.evaluate(async () => window.compasDev.db.productos.filter((p) => p.nombre === 'Producto sin foto').first());
console.log('0) producto nuevo sin selector de íconos y con foto opcional:', ok(formularioSimple && nuevo?.foto === null && nuevo?.emoji === ''));
await page.getByText('Playera Calo').first().click();
await dlg.getByText('Foto del producto').waitFor();
const camara = await dlg.locator('input[type=file][capture=environment]').count();
await dlg.locator('input[type=file]:not([capture])').setInputFiles(DIR + 'archivos/grupo.jpg');
await dlg.locator('img[src^="data:image/jpeg"]').first().waitFor();
await page.screenshot({ path: DIR + 'salida/prod-form.png' });
await dlg.getByRole('button', { name: 'Guardar' }).click();
await page.waitForTimeout(500);
const prod = await page.evaluate(async () => (await window.compasDev.db.productos.toArray()).find((p) => p.nombre === 'Playera Calo'));
console.log('1) foto guardada pequeña y con cámara disponible:', ok(camara === 1 && prod.foto?.startsWith('data:image/jpeg') && prod.foto.length < 70000), prod.foto?.length);
console.log('2) la lista de productos la muestra:', ok((await page.locator('main img[src^="data:image/jpeg"]').count()) >= 1));
await page.getByRole('link', { name: 'Entrada' }).first().click();
await page.getByRole('button', { name: /^Tienda/ }).click();
await page.getByRole('dialog').getByRole('button', { name: /Agregar Playera Calo/ }).locator('img').waitFor();
console.log('3) en la caja aparece con su foto: OK');
await page.screenshot({ path: DIR + 'salida/prod-caja.png' });
console.log('errores:', errores.length ? errores : 'ninguno');
await browser.close();
