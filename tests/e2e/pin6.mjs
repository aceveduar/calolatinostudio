import { chromium } from 'playwright-core';
const browser = await chromium.launch({ channel: 'msedge' });
const page = await (await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, locale: 'es-MX' })).newPage();
const errores = []; page.on('pageerror', (e) => errores.push(e.message));
const ok = (c) => (c ? 'OK' : 'MAL');
const teclear = async (p) => { for (const d of p) await page.getByRole('button', { name: d, exact: true }).click(); };
const puntos = () => page.locator('span.h-4.w-4.rounded-full').count();
await page.goto('http://localhost:4173/');
await page.waitForFunction(() => !!window.compasDev);
await page.evaluate(() => window.compasDev.sembrar());
await page.reload();
await page.getByText('Monse', { exact: true }).click();
console.log('1) usuario con PIN viejo muestra 4 puntos:', ok((await puntos()) === 4));
await teclear('1111');
await page.getByPlaceholder(/Quién llegó|Buscar…/).waitFor({ timeout: 5000 });
console.log('2) PIN de 4 existente sigue entrando: OK');
await page.getByRole('button', { name: /cambiar usuario/i }).first().click();
await page.getByText('Dirección Calo', { exact: true }).click();
await teclear('1234');
await page.getByPlaceholder(/Quién llegó|Buscar…/).waitFor();
await page.evaluate(() => { history.pushState(null, '', '/ajustes/usuarios'); dispatchEvent(new PopStateEvent('popstate')); });
await page.getByRole('button', { name: 'Nuevo usuario' }).click();
const dlg = page.getByRole('dialog');
await dlg.locator('input').first().fill('Recepción Tarde');
const campo = dlg.locator('input[inputmode=numeric]');
await campo.fill('1234');
const guardar = dlg.getByRole('button', { name: 'Guardar' });
console.log('3) no acepta PIN nuevo de 4:', ok(await guardar.isDisabled()));
await campo.fill('482915');
console.log('4) acepta PIN de 6:', ok(await guardar.isEnabled()));
await guardar.click();
await page.getByText('Usuario guardado').waitFor();
await page.getByRole('button', { name: /cambiar usuario/i }).first().click();
await page.getByText('Recepción Tarde', { exact: true }).click();
console.log('5) usuario nuevo muestra 6 puntos:', ok((await puntos()) === 6));
await teclear('4829');
await page.waitForTimeout(400);
console.log('6) con 4 dígitos todavía no intenta entrar:', ok((await page.getByText('Escribe tu PIN').count()) === 1));
await teclear('15');
await page.getByPlaceholder(/Quién llegó|Buscar…/).waitFor({ timeout: 5000 });
console.log('7) entra con los 6 dígitos: OK');
console.log('errores:', errores.length ? errores : 'ninguno');
await browser.close();
